from pathlib import Path
import json
ROOT = Path(__file__).resolve().parents[1]
core = ROOT / 'tokens/core'

def load(path):
    return json.loads(path.read_text(encoding='utf-8'))

def flatten(node, prefix=()):
    for key, value in node.items():
        if isinstance(value, dict) and '$value' in value:
            yield '-'.join(prefix + (key,)), value['$value']
        elif isinstance(value, dict):
            yield from flatten(value, prefix + (key,))

def css_value(v):
    if isinstance(v, dict) and 'value' in v and 'unit' in v:
        return f"{v['value']}{v['unit']}"
    if isinstance(v, dict) and {'color', 'offsetX', 'offsetY', 'blur', 'spread'} <= set(v):
        return ' '.join((
            css_value(v['offsetX']),
            css_value(v['offsetY']),
            css_value(v['blur']),
            css_value(v['spread']),
            v['color'],
        ))
    if isinstance(v, str) and v.startswith('{') and v.endswith('}'):
        return 'var(--aether-' + v[1:-1].replace('.', '-') + ')'
    return str(v)

base = []
for file in sorted(core.glob('*.json')):
    base.extend(f'  --aether-{key}: {css_value(value)};' for key, value in flatten(load(file)))
base.extend(f'  --aether-{key}: {css_value(value)};' for key, value in flatten(load(ROOT/'tokens/components/button.json')))
lines = [':root {', *base, '}']
for mode in ('light', 'dark'):
    vals = [f'  --aether-{key}: {css_value(value)};' for key, value in flatten(load(ROOT/f'tokens/semantic/{mode}.json'))]
    lines += [f'[data-theme="{mode}"] {{', *vals, '}']
lines += ['@media (prefers-color-scheme: dark) {', '  :root:not([data-theme]) {']
lines += [f'    --aether-{key}: {css_value(value)};' for key, value in flatten(load(ROOT/'tokens/semantic/dark.json'))]
lines += ['  }', '}']
content = '/* Generated by scripts/build_css.py; do not edit directly. */\n'+'\n'.join(lines)+'\n'
outputs = (ROOT/'packages/tokens-css/tokens.css', ROOT/'docs/tokens.css')
for out in outputs:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content, encoding='utf-8')
    print(out)
